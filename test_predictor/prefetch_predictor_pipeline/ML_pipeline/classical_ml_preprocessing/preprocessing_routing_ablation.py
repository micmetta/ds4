#!/usr/bin/env python3
"""Create controlled routing-history-only datasets for classical ML ablations."""

import argparse
import json
from pathlib import Path
from typing import Any

import joblib
import numpy as np
import pandas as pd
from scipy import sparse
from sklearn.preprocessing import OneHotEncoder, StandardScaler


SPLITS = ("train", "validation", "test")
TOP_K = 6
NUM_EXPERTS = 256
MIN_FREQUENCY = 41

SCRIPT_DIR = Path(__file__).resolve().parent
PIPELINE_ROOT = SCRIPT_DIR.parent.parent
DEFAULT_TRAINING_DIR = PIPELINE_ROOT / "build_dataset_2" / "ml" / "training"

ROUTING_COLUMNS = [f"routing_history_expert_{index}" for index in range(TOP_K)]
ROUTER_ID_COLUMNS = [f"router_logit_expert_id_{index}" for index in range(16)]
ROUTER_VALUE_COLUMNS = [f"router_logit_value_{index}" for index in range(16)]
HIDDEN_PCA_COLUMNS = [f"hidden_pca_{index}" for index in range(64)]
KV_CURRENT_COLUMNS = [
    "kv_current_l2_norm",
    "kv_current_rms",
    "kv_current_mean",
    "kv_current_std",
    "kv_current_max_abs",
]


def leggi_argomenti() -> argparse.Namespace:
    """
    Read the selected routing representation and input/output directories.

    Args:
        No Python arguments. Configuration is received from ``--representation``,
        ``--training-dir`` and ``--output-dir``.

    Returns:
        Namespace containing the controlled ablation configuration.
    """
    parser = argparse.ArgumentParser(
        description="Crea dataset classici con la sola routing history H=1."
    )
    parser.add_argument(
        "--representation",
        required=True,
        choices=(
            "slots_onehot",
            "multihot_256",
            "multihot_256_layer",
            "multihot_256_layer_router_state",
            "multihot_256_layer_router_state_hidden_pca64",
            "multihot_256_layer_router_state_kv_current",
        ),
        help=(
            "slots_onehot conserva i sei slot Top-6; multihot_256 conserva "
            "solo l'insieme dei sei expert in 256 posizioni; "
            "multihot_256_layer aggiunge il layer routed come one-hot; "
            "multihot_256_layer_router_state aggiunge layer, ID e valori "
            "dei 16 raw router logits; "
            "multihot_256_layer_router_state_hidden_pca64 aggiunge anche "
            "le 64 hidden feature PCA; multihot_256_layer_router_state_kv_current "
            "aggiunge le cinque statistiche KV current."
        ),
    )
    parser.add_argument(
        "--training-dir",
        type=Path,
        default=DEFAULT_TRAINING_DIR,
        help="Cartella build_dataset_N/ml/training con Parquet e label y_*.npy.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        required=True,
        help="Cartella dell'ablation in cui salvare arrays/ e artifacts/.",
    )
    return parser.parse_args()


def trova_parquet_base(training_dir: Path) -> Path:
    """
    Find the single Parquet table generated by the generic preprocessing step.

    Args:
        training_dir: Directory containing exactly one ``prefetch_training``
            Parquet table.

    Returns:
        Path of the compatible Parquet file.

    Raises:
        FileNotFoundError: If no compatible Parquet file exists.
        ValueError: If more than one compatible Parquet file exists.
    """
    candidates = sorted(training_dir.glob("prefetch_training*.parquet"))
    if not candidates:
        raise FileNotFoundError(
            f"Nessun Parquet prefetch_training*.parquet trovato in: {training_dir}"
        )
    if len(candidates) != 1:
        raise ValueError(
            "Trovati piu' Parquet compatibili; la cartella deve contenerne uno solo: "
            f"{[path.name for path in candidates]}"
        )
    return candidates[0]


def carica_tabella_base(
    training_dir: Path,
    include_hidden_pca: bool,
    include_kv_current: bool,
) -> pd.DataFrame:
    """
    Load the base table and validate the H=1 routing-history columns.

    Args:
        training_dir: Directory produced by ``preprocess_dataset.py``.

    Returns:
        DataFrame with the split assignment and six routing-history IDs.

    Raises:
        ValueError: If required columns or one of the three expected splits is
            missing.
    """
    required_columns = [
        "split",
        "layer",
        *ROUTING_COLUMNS,
        *ROUTER_ID_COLUMNS,
        *ROUTER_VALUE_COLUMNS,
    ]
    if include_hidden_pca:
        required_columns.extend(HIDDEN_PCA_COLUMNS)
    if include_kv_current:
        required_columns.extend(KV_CURRENT_COLUMNS)
    table = pd.read_parquet(trova_parquet_base(training_dir), columns=required_columns)
    missing_splits = set(SPLITS) - set(table["split"].unique())
    if missing_splits:
        raise ValueError(f"Split mancanti nel Parquet: {sorted(missing_splits)}")
    router_ids = table[ROUTER_ID_COLUMNS].to_numpy(dtype=np.int16)
    if np.any(router_ids < 0) or np.any(router_ids >= NUM_EXPERTS):
        raise ValueError("Gli ID dei raw router logits devono essere compresi tra 0 e 255.")
    if include_hidden_pca:
        hidden_pca = table[HIDDEN_PCA_COLUMNS].to_numpy(dtype=np.float32)
        if not np.isfinite(hidden_pca).all():
            raise ValueError("Le hidden feature PCA devono essere tutte finite.")
    if include_kv_current:
        kv_current = table[KV_CURRENT_COLUMNS].to_numpy(dtype=np.float32)
        if not np.isfinite(kv_current).all():
            raise ValueError("Le feature KV current devono essere tutte finite.")
    return table


def carica_e_verifica_label(
    training_dir: Path,
    split: str,
    split_table: pd.DataFrame,
) -> np.ndarray:
    """
    Load and validate the existing multi-label target of one split.

    Args:
        training_dir: Directory containing ``arrays/y_<split>.npy``.
        split: Split name: ``train``, ``validation`` or ``test``.
        split_table: Rows of the Parquet table assigned to the same split.

    Returns:
        Unsigned 8-bit multi-hot target with shape ``[N_split, 256]``.

    Raises:
        FileNotFoundError: If the target file does not exist.
        ValueError: If shape, type or number of active target experts is invalid.
    """
    label_path = training_dir / "arrays" / f"y_{split}.npy"
    if not label_path.is_file():
        raise FileNotFoundError(f"Label non trovate: {label_path}")

    labels = np.load(label_path)
    if labels.shape != (len(split_table), NUM_EXPERTS):
        raise ValueError(
            f"{split}: shape label inattesa {labels.shape}; "
            f"attesa {(len(split_table), NUM_EXPERTS)}"
        )
    if labels.dtype != np.uint8:
        raise ValueError(f"{split}: label dtype inatteso {labels.dtype}")
    if not np.all(labels.sum(axis=1) == TOP_K):
        raise ValueError(f"{split}: ogni label deve avere esattamente {TOP_K} valori attivi")
    return labels


def crea_encoder_slot() -> OneHotEncoder:
    """
    Create the categorical encoder used by the ordered-slot ablation.

    Args:
        No Python arguments. The frequency policy matches the existing
            classical preprocessing for a fair comparison.

    Returns:
        Sparse OneHotEncoder for the six distinct Top-6 slots.
    """
    return OneHotEncoder(
        handle_unknown="infrequent_if_exist",
        min_frequency=MIN_FREQUENCY,
        sparse_output=True,
        dtype=np.float32,
    )


def crea_encoder_layer() -> OneHotEncoder:
    """
    Create the train-fitted one-hot encoder for the routed layer column.

    Args:
        No Python arguments. The policy matches the progressive KNN ablation.

    Returns:
        Sparse OneHotEncoder for the categorical ``layer`` column.
    """
    return OneHotEncoder(
        handle_unknown="infrequent_if_exist",
        min_frequency=MIN_FREQUENCY,
        sparse_output=True,
        dtype=np.float32,
    )


def crea_scaler_router_values() -> StandardScaler:
    """
    Create the train-fitted scaler for the 16 raw router-logit values.

    Args:
        No Python arguments. The scaler is fit only on the train split.

    Returns:
        StandardScaler for the numerical router-state values.
    """
    return StandardScaler()


def crea_scaler_hidden_pca() -> StandardScaler:
    """Create the train-fitted scaler for the 64 PCA hidden features."""
    return StandardScaler()


def crea_scaler_kv_current() -> StandardScaler:
    """Create the train-fitted scaler for the five direct current-KV statistics."""
    return StandardScaler()


def crea_encoder_router_ids() -> OneHotEncoder:
    """
    Create a fixed 256-way one-hot encoder for every raw router-logit slot.

    Args:
        No Python arguments. Each of the 16 slots always supports every expert
        ID from 0 to 255, independently of categories observed in train.

    Returns:
        OneHotEncoder with 16 fixed category spaces of size 256.
    """
    categories = [np.arange(NUM_EXPERTS) for _ in ROUTER_ID_COLUMNS]
    return OneHotEncoder(
        categories=categories,
        handle_unknown="error",
        sparse_output=True,
        dtype=np.float32,
    )


def crea_multihot(table: pd.DataFrame) -> sparse.csr_matrix:
    """
    Convert six H=1 routing IDs into one order-independent 256-way multi-hot row.

    Args:
        table: One split containing ``routing_history_expert_0`` through ``_5``.

    Returns:
        CSR float32 matrix with shape ``[N, 256]`` and exactly six active
        values equal to one per row.

    Raises:
        ValueError: If an expert ID is outside ``[0, 255]`` or a row contains
            duplicate routing experts.
    """
    expert_ids = table[ROUTING_COLUMNS].to_numpy(dtype=np.int16)
    if np.any(expert_ids < 0) or np.any(expert_ids >= NUM_EXPERTS):
        raise ValueError("Gli ID nella routing history devono essere compresi tra 0 e 255.")
    if np.any(np.diff(np.sort(expert_ids, axis=1), axis=1) == 0):
        raise ValueError("Ogni routing history deve contenere sei expert distinti.")

    row_indices = np.repeat(np.arange(len(table), dtype=np.int32), TOP_K)
    column_indices = expert_ids.reshape(-1).astype(np.int32)
    values = np.ones(len(row_indices), dtype=np.float32)
    matrix = sparse.csr_matrix(
        (values, (row_indices, column_indices)),
        shape=(len(table), NUM_EXPERTS),
        dtype=np.float32,
    )
    if not np.all(np.diff(matrix.indptr) == TOP_K):
        raise ValueError("Ogni riga multi-hot deve avere esattamente sei valori attivi.")
    return matrix


def salva_output(
    output_dir: Path,
    representation: str,
    matrices: dict[str, sparse.csr_matrix],
    labels: dict[str, np.ndarray],
    encoder: OneHotEncoder | None,
    scaler: StandardScaler | None,
    router_id_encoder: OneHotEncoder | None,
    hidden_pca_scaler: StandardScaler | None,
    kv_current_scaler: StandardScaler | None,
) -> None:
    """
    Save ablation matrices, labels and representation-specific artifacts.

    Args:
        output_dir: Destination directory of one ablation.
        representation: Selected routing ablation representation.
        matrices: Mapping from split name to its CSR feature matrix.
        labels: Mapping from split name to its verified multi-hot target.
        encoder: Train-fitted encoder for representations that use one-hot
            columns; ``None`` for the direct multi-hot representation.
        scaler: Train-fitted scaler for raw router-logit values; ``None`` when
            the representation has no numerical router state.
        router_id_encoder: Fixed-category encoder for router-logit expert IDs;
            ``None`` when the representation has no router state.
        hidden_pca_scaler: Train-fitted scaler for the 64 PCA hidden values;
            ``None`` when the representation does not use hidden features.
        kv_current_scaler: Train-fitted scaler for the five current-KV
            statistics; ``None`` when the representation does not use them.

    Returns:
        None. Creates ``arrays/`` and ``artifacts/`` under ``output_dir``.
    """
    arrays_dir = output_dir / "arrays"
    artifacts_dir = output_dir / "artifacts"
    arrays_dir.mkdir(parents=True, exist_ok=True)
    artifacts_dir.mkdir(parents=True, exist_ok=True)

    for split in SPLITS:
        sparse.save_npz(arrays_dir / f"X_classic_{split}.npz", matrices[split])
        np.save(arrays_dir / f"y_{split}.npy", labels[split])

    if representation == "slots_onehot":
        if encoder is None:
            raise ValueError("L'ablation slots_onehot richiede un OneHotEncoder.")
        joblib.dump(encoder, artifacts_dir / "categorical_encoder.joblib")
        feature_names = encoder.get_feature_names_out(ROUTING_COLUMNS).tolist()
    elif representation == "multihot_256_layer":
        if encoder is None:
            raise ValueError("L'ablation multihot_256_layer richiede un OneHotEncoder.")
        joblib.dump(encoder, artifacts_dir / "categorical_encoder.joblib")
        feature_names = [
            *[f"routing_history_multihot_expert_{index}" for index in range(NUM_EXPERTS)],
            *encoder.get_feature_names_out(["layer"]).tolist(),
        ]
    elif representation in (
        "multihot_256_layer_router_state",
        "multihot_256_layer_router_state_hidden_pca64",
        "multihot_256_layer_router_state_kv_current",
    ):
        if encoder is None or scaler is None or router_id_encoder is None:
            raise ValueError("L'ablation router state richiede encoder, scaler e ID encoder.")
        joblib.dump(encoder, artifacts_dir / "categorical_encoder.joblib")
        joblib.dump(scaler, artifacts_dir / "numeric_scaler.joblib")
        joblib.dump(router_id_encoder, artifacts_dir / "router_id_encoder.joblib")
        feature_names = [
            *[f"routing_history_multihot_expert_{index}" for index in range(NUM_EXPERTS)],
            *encoder.get_feature_names_out(["layer"]).tolist(),
            *router_id_encoder.get_feature_names_out(ROUTER_ID_COLUMNS).tolist(),
            *ROUTER_VALUE_COLUMNS,
        ]
        if representation == "multihot_256_layer_router_state_hidden_pca64":
            if hidden_pca_scaler is None:
                raise ValueError("L'ablation hidden PCA richiede il relativo scaler.")
            joblib.dump(hidden_pca_scaler, artifacts_dir / "hidden_pca_scaler.joblib")
            feature_names.extend(HIDDEN_PCA_COLUMNS)
        if representation == "multihot_256_layer_router_state_kv_current":
            if kv_current_scaler is None:
                raise ValueError("L'ablation KV current richiede il relativo scaler.")
            joblib.dump(kv_current_scaler, artifacts_dir / "kv_current_scaler.joblib")
            feature_names.extend(KV_CURRENT_COLUMNS)
    else:
        feature_names = [f"routing_history_multihot_expert_{index}" for index in range(NUM_EXPERTS)]

    (artifacts_dir / "feature_names.json").write_text(
        json.dumps({"feature_names": feature_names}, indent=2) + "\n",
        encoding="utf-8",
    )
    summary: dict[str, Any] = {
        "ablation": "routing_history_only",
        "representation": representation,
        "source_columns": ROUTING_COLUMNS,
        "history_length": 1,
        "feature_count": len(feature_names),
        "target": "E_l(t+1)",
        "splits": {},
    }
    if representation in ("slots_onehot", "multihot_256_layer"):
        summary["one_hot_configuration"] = {
            "handle_unknown": "infrequent_if_exist",
            "min_frequency": MIN_FREQUENCY,
        }
    else:
        summary["multihot_dimension"] = NUM_EXPERTS
        summary["active_features_per_row"] = TOP_K

    if representation == "multihot_256_layer":
        summary["additional_columns"] = ["layer"]
        summary["layer_one_hot_feature_count"] = len(
            encoder.get_feature_names_out(["layer"])
        )
    if representation == "multihot_256_layer_router_state":
        summary["additional_columns"] = ["layer", *ROUTER_ID_COLUMNS, *ROUTER_VALUE_COLUMNS]
        summary["layer_one_hot_configuration"] = {
            "handle_unknown": "infrequent_if_exist",
            "min_frequency": MIN_FREQUENCY,
        }
        summary["router_state"] = {
            "layer_categorical_columns": ["layer"],
            "router_id_columns": ROUTER_ID_COLUMNS,
            "numeric_columns": ROUTER_VALUE_COLUMNS,
            "numeric_scaler": "StandardScaler fit only on train",
            "router_id_encoding": {
                "type": "fixed_one_hot_per_slot",
                "slots": len(ROUTER_ID_COLUMNS),
                "expert_id_range": [0, NUM_EXPERTS - 1],
                "feature_count": len(router_id_encoder.get_feature_names_out(ROUTER_ID_COLUMNS)),
            },
            "one_hot_feature_count": len(
                encoder.get_feature_names_out(["layer"])
            ),
        }
    if representation == "multihot_256_layer_router_state_hidden_pca64":
        summary["additional_columns"] = [
            "layer", *ROUTER_ID_COLUMNS, *ROUTER_VALUE_COLUMNS, *HIDDEN_PCA_COLUMNS
        ]
        summary["layer_one_hot_configuration"] = {
            "handle_unknown": "infrequent_if_exist",
            "min_frequency": MIN_FREQUENCY,
        }
        summary["router_state"] = {
            "layer_categorical_columns": ["layer"],
            "router_id_columns": ROUTER_ID_COLUMNS,
            "numeric_columns": ROUTER_VALUE_COLUMNS,
            "numeric_scaler": "StandardScaler fit only on train",
            "router_id_encoding": {
                "type": "fixed_one_hot_per_slot",
                "slots": len(ROUTER_ID_COLUMNS),
                "expert_id_range": [0, NUM_EXPERTS - 1],
                "feature_count": len(router_id_encoder.get_feature_names_out(ROUTER_ID_COLUMNS)),
            },
            "one_hot_feature_count": len(
                encoder.get_feature_names_out(["layer"])
            ),
        }
        summary["hidden_pca"] = {
            "columns": HIDDEN_PCA_COLUMNS,
            "input_dimension": len(HIDDEN_PCA_COLUMNS),
            "numeric_scaler": "StandardScaler fit only on train",
        }
    if representation == "multihot_256_layer_router_state_kv_current":
        summary["additional_columns"] = [
            "layer", *ROUTER_ID_COLUMNS, *ROUTER_VALUE_COLUMNS, *KV_CURRENT_COLUMNS
        ]
        summary["layer_one_hot_configuration"] = {
            "handle_unknown": "infrequent_if_exist",
            "min_frequency": MIN_FREQUENCY,
        }
        summary["router_state"] = {
            "layer_categorical_columns": ["layer"],
            "router_id_columns": ROUTER_ID_COLUMNS,
            "numeric_columns": ROUTER_VALUE_COLUMNS,
            "numeric_scaler": "StandardScaler fit only on train",
            "router_id_encoding": {
                "type": "fixed_one_hot_per_slot",
                "slots": len(ROUTER_ID_COLUMNS),
                "expert_id_range": [0, NUM_EXPERTS - 1],
                "feature_count": len(router_id_encoder.get_feature_names_out(ROUTER_ID_COLUMNS)),
            },
            "one_hot_feature_count": len(encoder.get_feature_names_out(["layer"])),
        }
        summary["kv_features_current"] = {
            "columns": KV_CURRENT_COLUMNS,
            "input_dimension": len(KV_CURRENT_COLUMNS),
            "numeric_scaler": "StandardScaler fit only on train",
            "pca": False,
        }

    for split in SPLITS:
        matrix = matrices[split]
        summary["splits"][split] = {
            "X_shape": list(matrix.shape),
            "X_nonzero_values": int(matrix.nnz),
            "y_shape": list(labels[split].shape),
        }
    (artifacts_dir / "preprocessing_summary.json").write_text(
        json.dumps(summary, indent=2) + "\n",
        encoding="utf-8",
    )


def main() -> None:
    """
    Build one controlled routing-history-only classical ML ablation.

    Args:
        No Python arguments. The selected representation and paths are read by
            ``leggi_argomenti()``.

    Returns:
        None. Writes CSR matrices and reusable artifacts without training a
        machine-learning model.
    """
    args = leggi_argomenti()

    print("1) Carico il Parquet base con la sola routing history H=1...")
    include_hidden_pca = args.representation == "multihot_256_layer_router_state_hidden_pca64"
    include_kv_current = args.representation == "multihot_256_layer_router_state_kv_current"
    table = carica_tabella_base(args.training_dir, include_hidden_pca, include_kv_current)
    split_tables = {
        split: table.loc[table["split"] == split].reset_index(drop=True)
        for split in SPLITS
    }
    print(f"   Esempi totali: {len(table):,}")

    print("2) Carico e verifico le label multi-label originali...")
    labels = {
        split: carica_e_verifica_label(args.training_dir, split, split_tables[split])
        for split in SPLITS
    }

    print(f"3) Creo la rappresentazione {args.representation}...")
    encoder: OneHotEncoder | None = None
    scaler: StandardScaler | None = None
    router_id_encoder: OneHotEncoder | None = None
    hidden_pca_scaler: StandardScaler | None = None
    kv_current_scaler: StandardScaler | None = None
    if args.representation == "slots_onehot":
        encoder = crea_encoder_slot()
        encoder.fit(split_tables["train"][ROUTING_COLUMNS])
        matrices = {
            split: encoder.transform(split_tables[split][ROUTING_COLUMNS]).tocsr()
            for split in SPLITS
        }
    elif args.representation == "multihot_256":
        matrices = {split: crea_multihot(split_tables[split]) for split in SPLITS}
    elif args.representation == "multihot_256_layer":
        encoder = crea_encoder_layer()
        encoder.fit(split_tables["train"][["layer"]])
        matrices = {
            split: sparse.hstack(
                [
                    crea_multihot(split_tables[split]),
                    encoder.transform(split_tables[split][["layer"]]).tocsr(),
                ],
                format="csr",
                dtype=np.float32,
            )
            for split in SPLITS
        }
    elif args.representation == "multihot_256_layer_router_state":
        encoder = crea_encoder_layer()
        encoder.fit(split_tables["train"][["layer"]])
        router_id_encoder = crea_encoder_router_ids()
        router_id_encoder.fit(split_tables["train"][ROUTER_ID_COLUMNS])
        scaler = crea_scaler_router_values()
        scaler.fit(split_tables["train"][ROUTER_VALUE_COLUMNS])
        matrices = {
            split: sparse.hstack(
                [
                    crea_multihot(split_tables[split]),
                    encoder.transform(split_tables[split][["layer"]]).tocsr(),
                    router_id_encoder.transform(split_tables[split][ROUTER_ID_COLUMNS]).tocsr(),
                    sparse.csr_matrix(
                        scaler.transform(split_tables[split][ROUTER_VALUE_COLUMNS]).astype(
                            np.float32
                        )
                    ),
                ],
                format="csr",
                dtype=np.float32,
            )
            for split in SPLITS
        }
    elif args.representation == "multihot_256_layer_router_state_hidden_pca64":
        encoder = crea_encoder_layer()
        encoder.fit(split_tables["train"][["layer"]])
        router_id_encoder = crea_encoder_router_ids()
        router_id_encoder.fit(split_tables["train"][ROUTER_ID_COLUMNS])
        scaler = crea_scaler_router_values()
        scaler.fit(split_tables["train"][ROUTER_VALUE_COLUMNS])
        hidden_pca_scaler = crea_scaler_hidden_pca()
        hidden_pca_scaler.fit(split_tables["train"][HIDDEN_PCA_COLUMNS])
        matrices = {
            split: sparse.hstack(
                [
                    crea_multihot(split_tables[split]),
                    encoder.transform(split_tables[split][["layer"]]).tocsr(),
                    router_id_encoder.transform(split_tables[split][ROUTER_ID_COLUMNS]).tocsr(),
                    sparse.csr_matrix(
                        scaler.transform(split_tables[split][ROUTER_VALUE_COLUMNS]).astype(
                            np.float32
                        )
                    ),
                    sparse.csr_matrix(
                        hidden_pca_scaler.transform(split_tables[split][HIDDEN_PCA_COLUMNS]).astype(
                            np.float32
                        )
                    ),
                ],
                format="csr",
                dtype=np.float32,
            )
            for split in SPLITS
        }
    else:
        encoder = crea_encoder_layer()
        encoder.fit(split_tables["train"][["layer"]])
        router_id_encoder = crea_encoder_router_ids()
        router_id_encoder.fit(split_tables["train"][ROUTER_ID_COLUMNS])
        scaler = crea_scaler_router_values()
        scaler.fit(split_tables["train"][ROUTER_VALUE_COLUMNS])
        kv_current_scaler = crea_scaler_kv_current()
        kv_current_scaler.fit(split_tables["train"][KV_CURRENT_COLUMNS])
        matrices = {
            split: sparse.hstack(
                [
                    crea_multihot(split_tables[split]),
                    encoder.transform(split_tables[split][["layer"]]).tocsr(),
                    router_id_encoder.transform(split_tables[split][ROUTER_ID_COLUMNS]).tocsr(),
                    sparse.csr_matrix(
                        scaler.transform(split_tables[split][ROUTER_VALUE_COLUMNS]).astype(np.float32)
                    ),
                    sparse.csr_matrix(
                        kv_current_scaler.transform(split_tables[split][KV_CURRENT_COLUMNS]).astype(np.float32)
                    ),
                ],
                format="csr",
                dtype=np.float32,
            )
            for split in SPLITS
        }

    print("4) Salvo matrici sparse, label e artefatti...")
    salva_output(
        args.output_dir,
        args.representation,
        matrices,
        labels,
        encoder,
        scaler,
        router_id_encoder,
        hidden_pca_scaler,
        kv_current_scaler,
    )

    print("\nPreprocessing routing ablation completato.")
    for split in SPLITS:
        matrix = matrices[split]
        print(f"{split}: X={matrix.shape}, nnz={matrix.nnz:,}, y={labels[split].shape}")
    print(f"Output: {args.output_dir}")


if __name__ == "__main__":
    main()
